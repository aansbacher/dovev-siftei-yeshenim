let ok = 0, fail = 0

const { data: before } = await supabase
  .from('tzaddikim').select('id').eq('hebrew_month', 'אדר')
  .not('biography','is',null).not('story','is',null).not('torah','is',null).not('quote','is',null).limit(500)

for (const rec of records) {
  const { error } = await supabase.from('tzaddikim').update(rec).eq('id', rec.id)
  if (error) { console.error(`✗ ${rec.id}:`, error.message); fail++ }
  else { process.stdout.write(`✓${rec.id} `); ok++ }
}
console.log()

