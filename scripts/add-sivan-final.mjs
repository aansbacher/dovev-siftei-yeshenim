async function main() {
  const MONTH = 'סיון'

  // Snapshot before
  const { data: before } = await supabase
    .from('tzaddikim')
    .select('id, popular_name, biography, story, torah, quote')
    .eq('hebrew_month', MONTH)

  const isComplete = r => r.biography && r.story && r.torah && r.quote
  const completeBefore = before.filter(isComplete).length
  console.log(`\n📊 לפני: ${completeBefore}/${before.length} שלמות`)

  // Apply updates
  console.log(`\n⚙️  מעדכן ${updates.length} רשומות...`)
  let ok = 0, fail = 0
  for (const { id, ...fields } of updates) {
    const { error } = await supabase.from('tzaddikim').update(fields).eq('id', id)
    if (error) { console.error(`  ✗ id=${id}: ${error.message}`); fail++ }
    else {
      const name = before.find(r => r.id === id)?.popular_name ?? id
      console.log(`  ✓ id=${id} — ${name}`)
      ok++
    }
  }

  // Snapshot after
  const { data: after } = await supabase
    .from('tzaddikim')
    .select('id, popular_name, full_name, hebrew_day, biography, story, torah, quote, image_url')
    .eq('hebrew_month', MONTH)
    .order('hebrew_day')

  const completeAfter = after.filter(isComplete).length
  const stillMissing = after.filter(r => !isComplete(r))

  // Summary
  console.log(`\n${'═'.repeat(60)}`)
  console.log(`📋  סיכום סופי — חודש ${MONTH}`)
  console.log('═'.repeat(60))
  console.log(`  לפני: ${completeBefore} שלמות | אחרי: ${completeAfter} שלמות`)
  console.log(`  עודכנו: ${ok} | נכשלו: ${fail}`)
  console.log(`  ללא תמונה: ${after.filter(r => !r.image_url).length}`)

  if (stillMissing.length > 0) {
    console.log(`\n⚠️  נותרו ${stillMissing.length} חסרות — לבדיקה ידנית:`)
    for (const r of stillMissing) {
      const missing = []
      if (!r.biography) missing.push('ביוגרפיה')
      if (!r.story)     missing.push('סיפור')
      if (!r.torah)     missing.push('תורה')
      if (!r.quote)     missing.push('ציטוט')
      console.log(`  [${r.hebrew_day}] id=${r.id}  ${(r.popular_name ?? r.full_name ?? '—').padEnd(30)}  חסר: ${missing.join(', ')}`)
    }
  } else {
    console.log('\n✅  חודש סיוון הושלם במלואו!')
  }

  console.log('═'.repeat(60))
}

main().catch(err => { console.error(err); process.exit(1) })
