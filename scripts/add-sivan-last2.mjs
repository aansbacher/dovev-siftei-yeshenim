let success = 0
for (const u of updates) {
  const { id, ...fields } = u
  const { error } = await supabase.from('tzaddikim').update(fields).eq('id', id)
  if (error) {
    console.error(`✗ id=${id}`, error.message)
  } else {
    console.log(`✓ id=${id}`)
    success++
  }
}

// Final count
const { data: all } = await supabase
  .from('tzaddikim')
  .select('id,biography,story,torah,quote')
  .eq('hebrew_month', 'סיון')

const complete = all.filter(r => r.biography && r.story && r.torah && r.quote)
