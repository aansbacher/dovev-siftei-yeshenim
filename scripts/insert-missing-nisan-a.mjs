function parseEnv(f) {
  return fs.readFileSync(f, 'utf8').split(/\r?\n/).reduce((e, l) => {
    const c = l.trim(); if (!c || c.startsWith('#')) return e
    const [k, ...r] = c.split('='); e[k.trim()] = r.join('=').trim(); return e
  }, {})
}
